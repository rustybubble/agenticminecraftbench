const mineflayer=require('mineflayer'); const {pathfinder,Movements}=require('mineflayer-pathfinder')
const mcDataFor=require('minecraft-data'); const {Observer}=require('../src/observe'); const {Executor}=require('../src/executor')
const bot=mineflayer.createBot({host:'127.0.0.1',port:25576,username:'SplitAgent',version:'1.16.5',auth:'offline'})
bot.loadPlugin(pathfinder)
bot.once('spawn',async()=>{
 const mc=mcDataFor(bot.version); const mv=new Movements(bot,mc); mv.canDig=true; mv.liquidCost=-1; bot.pathfinder.setMovements(mv)
 const ob=new Observer(bot,mc); const ex=new Executor({bot,mcData:mc,observer:ob,log:e=>{if(e.type!=='skill_start')console.log(e.type,e.skill||e.msg||'',e.error||JSON.stringify(e.result||{}).slice(0,200))},timeoutMs:60000})
 console.log('inv', bot.inventory.items().map(i=>i.name+'x'+i.count).join(','))
 const r=await ex.run({name:'light_portal',args:{}})
 console.log('RESULT', JSON.stringify(r.result))
 const p=bot.findBlock({matching:mc.blocksByName.nether_portal.id,maxDistance:24})
 console.log('portal block near?', p && p.position)
 bot.quit();process.exit(0)
})
setTimeout(()=>{console.log('timeout');process.exit(1)},70000)
